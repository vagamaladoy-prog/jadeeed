// Reads the cut-out front shots (public/wardrobe/*-front.webp) and records each garment's top outline,
// so the wooden hanger can be drawn to sit inside the shirt instead of sticking out of it.
// Output: src/components/home/wardrobe-shoulders.ts — per shot, 21 samples from the centre (u = 0) to the
// side edge (u = 1) of the image: the y of the garment's top edge, as a share of the image height.
// Run after scripts/process-wardrobe.mjs:  node scripts/wardrobe-shoulders.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "public/wardrobe");
const N = 20;
const out = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith("-front.webp")).sort()) {
  const { data, info } = await sharp(join(dir, f)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const topAt = (x) => {
    for (let y = 0; y < h; y++) if (data[(y * w + x) * 4 + 3] > 128) return y;
    return h;
  };
  const cx = (w - 1) / 2;
  const profile = [];
  for (let i = 0; i <= N; i++) {
    const dx = (i / N) * cx;
    // the lower of the two sides, so the hanger fits under both shoulders
    profile.push(+(Math.max(topAt(Math.round(cx - dx)), topAt(Math.round(cx + dx))) / h).toFixed(3));
  }
  out[f.replace("-front.webp", "")] = profile;
}
writeFileSync(
  join(root, "src/components/home/wardrobe-shoulders.ts"),
  `// generated by scripts/wardrobe-shoulders.mjs — do not edit
// top edge of each front shot, centre → side edge (21 samples), as a share of the image height
export const WARDROBE_SHOULDERS: Record<string, number[]> = ${JSON.stringify(out)};
`,
);
console.log(out);
